// House standard: no third-party requests. This is a ratchet, not a scan — the
// hosts the app may reach are listed below with a reason, and anything new fails.
//
// It checks the BUILT output rather than the source on purpose: dist/ has comments
// stripped and dead code shaken out, so a host in there is a host the shipped app
// can actually reach, and a documentation link in a code comment is not a finding.
// Run it after `npm run build` (npm run verify does).
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

let problems = 0;
let checks = 0;
function check(cond, msg) {
  checks++;
  if (!cond) { console.log(`  x ${msg}`); problems++; }
}

if (!existsSync("dist/index.html")) {
  console.error("[validate-requests] no dist/ — run `npm run build` first (npm run verify does)");
  process.exit(1);
}

/**
 * Every host the shipped bundle may name, and why. Adding one here is a decision
 * about the app's privacy promise, which is exactly why it has to be made here
 * rather than by a request appearing in a diff.
 */
const ALLOWED = {
  "www.w3.org": "XML/SVG namespace URIs — identifiers, never fetched",
  "adervec.github.io": "the maker's own origin: font.js and the self-hosted fonts (same origin in production)",
  "accounts.google.com": "Google Identity Services, loaded lazily only when the user connects Drive",
  "www.googleapis.com": "Drive appdata REST API, only after opt-in + consent",
  "api.anthropic.com": "the optional Coach chat: user-supplied key, explicit consent, user-initiated",
  "oauth2.googleapis.com": "Google's OAuth token endpoint, reached by the Identity Services script during Drive sign-in (named in the CSP, so it is declared here too)",
  "github.com": "links to the source repo in the UI (and the vendored engine's SOURCE note)",
  "reactjs.org": "React's own error-message URL, inside a thrown string",
};

// dist/engine/* is a vendored upstream Stockfish build regenerated by
// scripts/setup-engine.mjs, not our code, and the .nnue net is 39 MB of binary.
const files = ["dist/index.html", "dist/404.html", "dist/sw.js", "dist/manifest.webmanifest"]
  .filter((f) => existsSync(f))
  .concat(
    existsSync("dist/assets")
      ? readdirSync("dist/assets").filter((f) => /\.(js|css|html)$/.test(f)).map((f) => join("dist/assets", f))
      : []
  );

check(files.length >= 4, `found the built files to scan (got ${files.length})`);

const hosts = new Map(); // host -> first file it appeared in
for (const file of files) {
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(/\bhttps?:\/\/([a-zA-Z0-9.-]+)/g)) {
    if (!hosts.has(m[1])) hosts.set(m[1], file);
  }
}

console.log(`Hosts named in the build (${hosts.size}):`);
for (const [host, file] of [...hosts].sort()) {
  const why = ALLOWED[host];
  console.log(`  ${why ? "·" : "x"} ${host}${why ? ` — ${why}` : ` — NOT ALLOWED (first seen in ${file})`}`);
  check(Boolean(why), `${host} is an undeclared third party (first seen in ${file})`);
}

console.log("\nNo asset CDNs:");
// Redundant with the allowlist, but it names the failure the standard cares about.
for (const cdn of [
  "fonts.googleapis.com", "fonts.gstatic.com", "cdn.jsdelivr.net",
  "unpkg.com", "cdnjs.cloudflare.com", "code.jquery.com", "use.typekit.net",
]) check(!hosts.has(cdn), `${cdn} is not referenced — fonts and libraries ship with the app`);

console.log("\nNothing external is pulled in at load:");
{
  const html = readFileSync("dist/index.html", "utf8");
  // The one external <script> is the house font.js, from the maker's own origin.
  const external = [...html.matchAll(/<(?:script|link)\b[^>]*?(?:src|href)="(https?:\/\/[^"]+)"/g)]
    .map((m) => m[1])
    .filter((u) => !u.startsWith("https://adervec.github.io/"));
  check(external.length === 0, `index.html loads nothing external beyond the house font (found ${external.join(", ")})`);

  const css = files.filter((f) => f.endsWith(".css")).map((f) => readFileSync(f, "utf8")).join("\n");
  check(!/@import\s+(?:url\()?["']?https?:/i.test(css), "the built CSS has no remote @import");
  check(!/url\(["']?https?:\/\/(?!adervec\.github\.io)/i.test(css), "the built CSS loads no remote fonts or images");
}

console.log(`\n[validate-requests] checks=${checks} problems=${problems}`);
process.exit(problems ? 1 : 0);
